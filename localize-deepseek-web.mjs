const comment = /^\s*(\/\/|\/\*|\*)/

const LITERAL = /(['"`])((?:\\.|(?!\1).)*?)\1/g

/**
 * Replace only literals whose entire text is a dictionary key. Whole-literal
 * matching keeps a partial phrase from corrupting a longer sentence.
 */
function patch(path, dry) {
  if (!existsSync(path)) return { file: path, applied: 0, missing: true }
  const source = readFileSync(path, 'utf8')
  let applied = 0
  const text = source.replace(LITERAL, (whole, quote, body) => {
    const english = DICT[body]
    if (english === undefined) return whole
    applied += 1
    return `${quote}${english}${quote}`
  })
  if (!dry && text !== source) writeFileSync(path, text)
  return { file: path, applied }
}

